function detectLocale() {
  if (typeof location === "undefined") return "en";
  const stored = typeof localStorage === "undefined" ? "" : localStorage.getItem(STORAGE_KEY);
  const requested = new URLSearchParams(location.search).get("lang") || stored || "en";
  return String(requested).toLowerCase().startsWith("pt") ? "pt" : "en";
}

export let locale = detectLocale();

export function localeTag() {
  return locale === "pt" ? "pt-BR" : "en";
}

export function translate(language, message, vars = {}) {
  const table = language === "pt" ? catalog.pt : null;
  let text = table?.[message] ?? message;
  for (const [key, value] of Object.entries(vars)) text = text.replaceAll(`{${key}}`, String(value ?? ""));
  return text;
}

export function t(message, vars) {
  return translate(locale, message, vars);
}

export function formatNumber(value) {
  return Number(value ?? 0).toLocaleString(localeTag());
}

export function formatDate(value) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "—";
  return new Intl.DateTimeFormat(localeTag(), { dateStyle: "medium" }).format(date);
}

export function formatShortDate(value) {
  return new Intl.DateTimeFormat(localeTag(), { day: "2-digit", month: "short", year: "2-digit", timeZone: "UTC" }).format(new Date(`${value}T12:00:00Z`));
}

export function applyDocument(root = typeof document === "undefined" ? null : document) {
  if (!root) return;
  root.documentElement.lang = locale === "pt" ? "pt-BR" : "en";
  root.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = t(element.dataset.i18nPlaceholder);
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", t(element.dataset.i18nAria));
  });
  root.querySelectorAll("[data-set-locale]").forEach((button) => {
    button.classList.toggle("active", button.dataset.setLocale === locale);
    button.setAttribute("aria-pressed", String(button.dataset.setLocale === locale));
  });
}

export function rememberLocale(next) {
  locale = next === "pt" ? "pt" : "en";
  if (typeof localStorage !== "undefined") localStorage.setItem(STORAGE_KEY, locale);
}
